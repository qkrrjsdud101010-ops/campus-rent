PROMPT [3/4] Creating 17 Oracle 11g sequences and insert triggers

CREATE SEQUENCE SQ_APP_USER
    START WITH 1 INCREMENT BY 1 MINVALUE 1 MAXVALUE 9999999999
    CACHE 20 NOCYCLE NOORDER;

CREATE TRIGGER BI_APP_USER
BEFORE INSERT ON APP_USER
FOR EACH ROW
BEGIN
    IF :NEW.USER_ID IS NULL THEN
        SELECT SQ_APP_USER.NEXTVAL INTO :NEW.USER_ID FROM DUAL;
    END IF;
END;
/
SHOW ERRORS TRIGGER BI_APP_USER

