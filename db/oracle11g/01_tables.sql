CREATE TABLE REQUEST_ITEM (
    REQUEST_ITEM_ID NUMBER(10) NOT NULL,
    REQUEST_ID NUMBER(10) NOT NULL,
    ITEM_NO NUMBER(3) NOT NULL,
    ITEM_KIND CHAR(1) NOT NULL,
    EQUIPMENT_ID NUMBER(10) NULL,
    FACILITY_ID NUMBER(10) NULL,
    USE_START_AT TIMESTAMP NOT NULL,
    USE_END_AT TIMESTAMP NOT NULL,
    PEOPLE_COUNT NUMBER(3) NULL,
    PURPOSE_ID NUMBER(10) NULL,
    ORIGIN_CODE VARCHAR2(10 CHAR) DEFAULT 'DIRECT' NOT NULL,
    ACTIVITY_TEXT VARCHAR2(1000 CHAR) NULL,
    STATUS_CODE VARCHAR2(20 CHAR) DEFAULT 'PENDING' NOT NULL,
    ROW_VERSION NUMBER(10) DEFAULT 0 NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT LOCALTIMESTAMP NOT NULL,
    CONSTRAINT PK_REQUEST_ITEM PRIMARY KEY (REQUEST_ITEM_ID),
    CONSTRAINT UQ_RI_NO UNIQUE (REQUEST_ID, ITEM_NO),
    CONSTRAINT UQ_RI_KIND UNIQUE (REQUEST_ITEM_ID, ITEM_KIND),
    CONSTRAINT CK_RI_ROW_VERSION CHECK (
        ROW_VERSION >= 0
    ),
    CONSTRAINT CK_RI_PEOPLE CHECK (
        PEOPLE_COUNT IS NULL OR PEOPLE_COUNT > 0
    ),
    CONSTRAINT CK_RI_ORIGIN CHECK (
        ORIGIN_CODE IN ('DIRECT','RECOMMEND','ALTERNATE')
    ),
    CONSTRAINT CK_RI_RESOURCE CHECK (
        (ITEM_KIND = 'E' AND EQUIPMENT_ID IS NOT NULL AND FACILITY_ID IS NULL)
        OR (ITEM_KIND = 'F' AND FACILITY_ID IS NOT NULL AND EQUIPMENT_ID IS NULL)
    ),
    CONSTRAINT CK_RI_PERIOD CHECK (
        USE_END_AT > USE_START_AT
    ),
    CONSTRAINT CK_RI_ITEM_NO CHECK (
        ITEM_NO > 0
    ),
    CONSTRAINT CK_RI_FAC_FIELDS CHECK (
        ITEM_KIND <> 'F' OR (PEOPLE_COUNT IS NOT NULL AND PURPOSE_ID IS NOT NULL)
    ),
    CONSTRAINT CK_RI_STATUS CHECK (
        (ITEM_KIND = 'E' AND STATUS_CODE IN
         ('PENDING','APPROVED','CHECKED_OUT','RETURN_REQUESTED','RETURN_HELD','RETURNED','REJECTED','CANCELLED'))
        OR (ITEM_KIND = 'F' AND STATUS_CODE IN
         ('PENDING','APPROVED','IN_USE','COMPLETED','REJECTED','CANCELLED'))
    )
);

COMMENT ON TABLE REQUEST_ITEM IS '개별신청항목';
